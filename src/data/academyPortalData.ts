  feesPerTerm?: string; // المصروفات للترم أو السنة
  totalFees?: string; // إجمالي المصروفات
  installmentDetails?: string; // تفاصيل ونظام الأقساط
  jobTitle?: string; // المسمى الوظيفي وكارنيه مزاولة المهنة
  requirements?: string; // شروط القبول
